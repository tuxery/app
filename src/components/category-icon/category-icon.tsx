/** The category's icon, decorative (the label always sits next to it). */
export const CategoryIcon = component$<{ category: string; class?: string }>(
  ({ category, class: className }) => {
    const Icon = Object.hasOwn(ICONS, category) ? ICONS[category as keyof typeof ICONS] : LuTag;
    return <Icon class={className} aria-hidden="true" />;
  },
);
